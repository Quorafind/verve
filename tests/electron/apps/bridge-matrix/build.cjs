// Builds preload.js from preload.src.js: a sandboxed preload cannot `require` a file, so the two
// files the page loads as scripts are inlined at its head. `node build.cjs` after editing either.
const fs = require('node:fs');
const read = (name) => fs.readFileSync(`${__dirname}/${name}`, 'utf8');
fs.writeFileSync(
  `${__dirname}/preload.js`,
  `// Generated by build.cjs from describe.js, cases.js and preload.src.js: do not edit.\n${read('describe.js')}\n${read('cases.js')}\n${read('preload.src.js')}`,
);
